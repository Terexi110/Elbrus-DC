SIGNED = {"i8": "char", "i16": "short", "i32": "int", "i64": "long", "i128": "__int128",
          "f32": "float", "f64": "double", "b": "int", "v": "void"}
UNSIGNED = {"i8": "unsigned char", "i16": "unsigned short", "i32": "unsigned int",
            "i64": "unsigned long", "i128": "unsigned __int128"}

PREC = {"||": 4, "&&": 5, "|": 6, "^": 7, "&": 8, "==": 9, "!=": 9,
        "<": 10, "<=": 10, ">": 10, ">=": 10, "<<": 11, ">>": 11,
        "+": 12, "-": 12, "*": 13, "/": 13, "%": 13}

CMP_C = {"==": "==", "!=": "!=", "<s": "<", "<=s": "<=", ">s": ">", ">=s": ">=",
         "<u": "<", "<=u": "<=", ">u": ">", ">=u": ">=",
         "<f": "<", "<=f": "<=", "==f": "==", "!=f": "!=", ">f": ">", ">=f": ">="}
ARITH_C = {"+": "+", "-": "-", "*": "*", "&": "&", "|": "|", "^": "^", "<<": "<<",
           ">>u": ">>", ">>s": ">>", "/s": "/", "/u": "/", "%s": "%", "%u": "%",
           "+f": "+", "-f": "-", "*f": "*", "/f": "/"}
UNSIGNED_OPS = {">>u", "/u", "%u", "<u", "<=u", ">u", ">=u"}
SIGNED_OPS = {">>s", "/s", "%s", "<s", "<=s", ">s", ">=s"}

