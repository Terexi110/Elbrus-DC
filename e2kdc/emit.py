def esc(s):
    out = []
    for ch in s:
        if ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ord(ch) < 32:
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def fmt_int(v, ty):
    bits = BITS.get(ty, 64)
    s = sext(v, bits)
    a = abs(s)
    body = str(a) if a < 4096 else hex(a)
    suf = "L" if bits == 64 and a > 0x7FFFFFFF else ""
    return ("-" if s < 0 else "") + body + suf


class Printer:
    def __init__(self, F, ctx):
        self.F, self.ctx = F, ctx
        self.indent = "    "

    # ---------------------------------------------------------- types
    def vtype(self, v):
        if getattr(v, "pointer", False) and v.ty == "i64":
            from .structs import rep
            S = rep(getattr(v, "struct", None))
            if S is not None and S.name:
                return "struct %s *" % S.name
            pt = pointee_ctype(v)
            return pt + ("*" if pt.endswith("*") else " *")
        if getattr(v, "unsigned", False) and v.ty in UNSIGNED:
            return UNSIGNED[v.ty]
        return SIGNED.get(v.ty, "long")

    def decl(self, v):
        """C declaration of a variable"""
        fp = getattr(v, "funcptr", None)
        if fp and v.ty == "i64":
            return "%s (*%s)()" % (SIGNED.get(fp, "long"), v.name)
        t = self.vtype(v)
        return "%s%s%s" % (t, "" if t.endswith("*") else " ", v.name)

    @staticmethod
    def paren(t, p, need):
        return t if p >= need else "(%s)" % t

    def typed_access(self, addr, ty, unsigned=False):
        """p[k] / *p when addr = p + k*sizeof(*p) and the access has p's element type."""
        r = split_addr(addr)
        if r is None:
            return None
        v, off = r
        S = getattr(v, "struct", None)
        if S is not None and S.name:
            return self.field_access(v, S, off, ty, unsigned)
        pe = getattr(v, "pointee", None)
        if not pe or ir_ty(pe) != ty or (unsigned and pe[0] != "u" and not is_float(ty)):
            return None
        k = scale_down(off, BITS[ty] // 8)
        if k is None:
            return None
        from .simplify import simplify
        k = simplify(k)
        ct = pointee_ctype(v)
        if isinstance(k, Const) and sext(k.value, 64) == 0:
            return "*" + v.name, 14, ct
        return "%s[%s]" % (v.name, self.e(k)), 15, ct

    def field_access(self, v, S, off, ty, unsigned):
        """p->fN, p[i].fN, p->fN[k], p->fN.fM for an access through pointer v"""
        return self.struct_access(v.name, True, S, off, ty, unsigned)

    def struct_access(self, name, is_ptr, S, off, ty, unsigned, count=None):
        """access of type ty at byte offset off from `name` (a pointer to S, or
        an object of type S / an array of `count` S)"""
        from .structs import const_part, lin, rep, field_path
        from .simplify import simplify
        S = rep(S)
        rest, c = const_part(lin(off))
        idx, fo = None, c
        if S.size and (is_ptr or count):
            q, fo = divmod(c, S.size)
            if rest is not None:
                k = scale_down(rest, S.size)
                if k is not None:
                    idx = simplify(Bin("+", k, Const(q, k.ty), k.ty)) if q else simplify(k)
                    rest = None
            elif q:
                idx = Const(q, "i64")
        r = field_path(S, fo, rest, ty, unsigned, self)
        if r is None:
            return None
        path, ct = r
        if idx is None and is_ptr:
            return "%s->%s" % (name, path), 15, ct
        if idx is None and count:
            idx = Const(0, "i64")
        if idx is None:
            return "%s.%s" % (name, path), 15, ct
        return "%s[%s].%s" % (name, self.e(idx), path), 15, ct

    def sym_struct_access(self, addr, ty, unsigned):
        """a global or stack object of structure type: obj.fN / obj[i].fN"""
        from .structs import const_part, lin
        rest, c = const_part(lin(addr))
        sym = None
        if isinstance(rest, Sym):
            sym, rest = rest, None
        elif isinstance(rest, Bin) and rest.op == "+":
            for x, y in ((rest.a, rest.b), (rest.b, rest.a)):
                if isinstance(x, Sym):
                    sym, rest = x, y
                    break
        if sym is None or sym.kind not in ("data", "local"):
            return None
        info = self.ctx.object_struct(sym, self.F)
        if info is None:
            return None
        name, S, count, base_off = info
        off = Const(c + base_off, "i64") if rest is None else Bin("+", rest, Const(c + base_off, "i64"), "i64")
        return self.struct_access(name, False, S, off, ty, unsigned, count)

    def field_address(self, pt, pp, pct, c):
        """p + c for a struct pointer: &p->fN (an array field decays: p->fN)"""
        from .structs import BYNAME, rep, field_ctype
        S = BYNAME.get(pct[7:-1].strip())
        if S is None:
            return None
        S = rep(S)
        f = S.fields.get(c)
        if f is None:
            return None
        ct = field_ctype(S, f)
        base = "%s->f%x" % (self.paren(pt, pp, 15), c)
        if f["count"] is not None and f["ty"] not in ("struct",):
            return base, 15, ct + " *"
        return "&" + base, 14, ct + ("*" if ct.endswith("*") else " *")

    def ptr_arith(self, x):
        """+/- with a typed pointer operand: C scales by the element size."""
        la, lp, lct = self.ex(x.a)
        ra, rp, rct = self.ex(x.b)
        lptr, rptr = lct.endswith("*"), rct.endswith("*")
        if lptr and rptr:
            if x.op == "-":
                return ("(char *)%s - (char *)%s" % (self.paren(la, lp, 14), self.paren(ra, rp, 14)), 12, "long")
            return None
        if lptr:
            pt, pp, pct, off = la, lp, lct, x.b
        elif rptr and x.op == "+":
            pt, pp, pct, off = ra, rp, rct, x.a
        else:
            return None
        size = elem_csize(pct)
        if pct.startswith("struct ") and not pct[:-1].strip().endswith("*"):
            k = scale_down(off, size) if size else None
            if k is None and isinstance(off, Const) and x.op == "+":
                fa = self.field_address(pt, pp, pct, sext(off.value, 64))
                if fa is not None:
                    return fa
            if k is None:                  # inside a structure: byte address
                return ("(char *)%s %s %s" % (self.paren(pt, pp, 14), "-" if x.op == "-" else "+",
                                               self.e(off, 13)), 12, "char *")
        if size == 1:
            return None
        k = scale_down(off, size)
        neg = x.op == "-"
        if k is not None:
            if isinstance(k, Const):
                v = sext(k.value, 64)
                if v == 0:
                    return pt, pp, pct
                if v < 0:
                    neg, k = not neg, Const(-v, "i64")
            return ("%s %s %s" % (self.paren(pt, pp, 12), "-" if neg else "+", self.e(k, 13)), 12, pct)
        return ("(%s)((char *)%s %s %s)" % (pct, self.paren(pt, pp, 14), "-" if neg else "+", self.e(off, 13)),
                14, pct)

    # ---------------------------------------------------------- expressions
    def e(self, x, prec=0):
        t, p, _ = self.ex(x)
        return "(%s)" % t if p < prec else t

    def ex(self, x):
        """-> (text, precedence, ctype)"""
        if isinstance(x, Const):
            if x.ty == "b":
                return (str(int(bool(x.value))), 16, "int")
            t = fmt_int(x.value, x.ty)
            return (t, 16 if not t.startswith("-") else 14, SIGNED.get(x.ty, "long"))
        if isinstance(x, FConst):
            r = repr(float(x.value))
            if r in ("inf", "-inf", "nan"):
                r = {"inf": "__builtin_inf()", "-inf": "-__builtin_inf()", "nan": "__builtin_nan(\"\")"}[r]
            elif "e" not in r and "." not in r:
                r += ".0"
            if x.ty == "f32":
                r += "f" if "builtin" not in r else ""
            return (r, 16 if not r.startswith("-") else 14, SIGNED[x.ty])
        if isinstance(x, Var):
            return (x.var.name, 16, self.vtype(x.var))
        if isinstance(x, Reg):
            return ("__" + x.name, 16, SIGNED.get(x.ty, "long"))
        if isinstance(x, Str):
            return (esc(x.text), 16, "char *")
        if isinstance(x, Sym):
            return self.sym_value(x)
        if isinstance(x, Load):
            return self.load(x)
        if isinstance(x, Cast):
            return self.cast(x)
        if isinstance(x, BitCast):
            return ("__bitcast_%s(%s)" % (SIGNED.get(x.ty, x.ty).replace(" ", "_"), self.e(x.a)), 16, SIGNED.get(x.ty, "long"))
        if isinstance(x, Un):
            if x.op == "!":
                return ("!" + self.e(x.a, 14), 14, "int")
            if x.op in ("-", "~"):
                t, p, ct = self.ex(x.a)
                ct = ct if ct == UNSIGNED.get(x.ty) else SIGNED.get(x.ty, "long")
                return (x.op + self.paren(t, p, 14), 14, ct)
            return ("%s%s" % (x.op, self.e(x.a, 14)), 14, "long")
        if isinstance(x, Bin):
            return self.binop(x)
        if isinstance(x, Select):
            at, ap, act = self.ex(x.a)
            bt, bp, bct = self.ex(x.b)
            ct = UNSIGNED[x.ty] if is_int(x.ty) and UNSIGNED.get(x.ty) in (act, bct) else SIGNED.get(x.ty, "long")
            return ("%s ? %s : %s" % (self.e(x.c, 4), self.paren(at, ap, 3), self.paren(bt, bp, 3)), 3, ct)
        if isinstance(x, Call):
            return self.call(x)
        if isinstance(x, Intr):
            return self.intr(x)
        return ("/*?%s*/" % type(x).__name__, 16, "long")

    def signed_operand(self, x, ty):
        t, p, ct = self.ex(x)
        if ct.startswith("unsigned") or ct.endswith("*"):
            return "(%s)%s" % (SIGNED.get(ty, "long"), t if p >= 14 else "(%s)" % t), 14
        return t, p

    def unsigned_operand(self, x, ty):
        if isinstance(x, Const):
            v = x.value & ((1 << BITS.get(ty, 64)) - 1)
            body = str(v) if v < 4096 else hex(v)
            return body + ("u" if BITS.get(ty, 64) <= 32 else "uL"), 16
        t, p, ct = self.ex(x)
        u = UNSIGNED.get(ty, "unsigned long")
        if ct == u:
            return t, p
        return "(%s)%s" % (u, t if p >= 14 else "(%s)" % t), 14

    def binop(self, x):
        op = x.op
        if op in ("&&", "||"):
            p = PREC[op]
            return ("%s %s %s" % (self.e(x.a, p), op, self.e(x.b, p + 1)), p, "int")
        if op in ("rotl", "rotr"):
            n = "__RO%s%d__" % ("L" if op == "rotl" else "R", 4 if x.ty == "i32" else 8)
            return ("%s(%s, %s)" % (n, self.e(x.a), self.e(x.b)), 16, UNSIGNED.get(x.ty, "unsigned long"))
        cop = CMP_C.get(op) or ARITH_C.get(op)
        if cop is None:
            return ("__op_%s(%s, %s)" % (op, self.e(x.a), self.e(x.b)), 16, "long")
        if op in ("+", "-") and is_int(x.ty):
            r = self.ptr_arith(x)
            if r is not None:
                return r
        if op in CMP_C and op not in ("<f", "<=f", "==f", "!=f", ">f", ">=f"):
            # pointers to different element types: compare as bytes
            la, lp, lct = self.ex(x.a)
            ra, rp, rct = self.ex(x.b)
            if lct.endswith("*") and rct.endswith("*") and lct != rct:
                p = PREC[cop]
                return ("(char *)%s %s (char *)%s" % (self.paren(la, lp, 14), cop, self.paren(ra, rp, 14)),
                        p, "int")
        p = PREC[cop]
        oty = x.a.ty if op in CMP_C else x.ty
        if op in UNSIGNED_OPS:
            if op == ">>u":
                lt, lp = self.unsigned_operand(x.a, oty)
                rt = self.e(x.b, p + 1)
            else:
                lt, lp = self.unsigned_operand(x.a, oty)
                rt, rp = self.unsigned_operand(x.b, oty)
                rt = rt if rp > p else "(%s)" % rt
            lt = lt if lp >= p else "(%s)" % lt
            ct = "int" if op in CMP_C else UNSIGNED.get(x.ty, "unsigned long")
            return ("%s %s %s" % (lt, cop, rt), p, ct)
        if op in SIGNED_OPS:
            lt, lp = self.signed_operand(x.a, oty)
            if op == ">>s":
                rt, rp = self.e(x.b, p + 1), 16
            else:
                rt, rp = self.signed_operand(x.b, oty)
            lt = lt if lp >= p else "(%s)" % lt
            rt = rt if rp > p else "(%s)" % rt
            ct = "int" if op in CMP_C else SIGNED.get(x.ty, "long")
            return ("%s %s %s" % (lt, cop, rt), p, ct)
        if cop == "*" and isinstance(x.b, Const) and isinstance(x.a, (Var, Cast)) and \
                (isinstance(x.a, Var) or isinstance(x.a.a, Var)):
            # 2 * i rather than i * 2 (same value, commutative)
            v = sext(x.b.value, BITS.get(x.ty, 64)) if is_int(x.ty) else None
            if v is not None and 0 < v < 1 << 16:
                t, tp, tct = self.ex(x.a)
                return ("%s * %s" % (fmt_int(v, x.ty), t if tp > p else "(%s)" % t), p, SIGNED.get(x.ty, "long"))
        la, lp, lct = self.ex(x.a)
        ra, rp, rct = self.ex(x.b)
        # a 64-bit result from a 32-bit C operand: C would compute in 32 bits
        # (u32 << 32 is undefined, int + int overflows first).  Widen explicitly.
        NARROW = ("int", "unsigned int", "short", "unsigned short", "char", "unsigned char")
        if x.ty == "i64" and lct in NARROW and (cop == "<<" or (cop in ("+", "-", "*") and rct in NARROW)):
            wt = "unsigned long" if lct.startswith("unsigned") else "long"
            la, lp, lct = "(%s)%s" % (wt, la if lp >= 14 else "(%s)" % la), 14, wt
        # pointer operands in non-additive arithmetic need an integer cast
        if lct.endswith("*") and cop not in ("+", "-", "==", "!="):
            la, lp = "(long)%s" % (la if lp >= 14 else "(%s)" % la), 14
        if rct.endswith("*") and cop not in ("==", "!=", "+"):
            ra, rp = "(long)%s" % (ra if rp >= 14 else "(%s)" % ra), 14
        if cop == "+" and isinstance(x.b, Const) and is_int(x.ty):
            v = sext(x.b.value, BITS[x.ty])
            if v < 0:
                return ("%s - %s" % (la if lp >= p else "(%s)" % la, fmt_int(-v, x.ty)), p,
                        lct if lct.endswith("*") else SIGNED.get(x.ty, "long"))
        la = la if lp >= p else "(%s)" % la
        ra = ra if rp > p else "(%s)" % ra
        if cop in ("==", "!=", "<", "<=", ">", ">="):
            ct = "int"
        elif lct.endswith("*") and cop in ("+", "-"):
            ct = lct
        elif is_int(x.ty) and UNSIGNED.get(x.ty) in (lct, rct) and cop not in ("<<", ">>"):
            ct = UNSIGNED[x.ty]          # C: an unsigned operand of the same rank wins
        elif is_int(x.ty) and cop in ("<<", ">>") and lct == UNSIGNED.get(x.ty):
            ct = UNSIGNED[x.ty]
        else:
            ct = SIGNED.get(x.ty, "long")
        return ("%s %s %s" % (la, cop, ra), p, ct)

    def cast(self, x):
        a = x.a
        if isinstance(a, Load) and is_int(a.ty) and is_int(x.ty) and BITS[x.ty] > BITS[a.ty]:
            ld = Load(a.addr, a.ty)
            t = self.mem(ld, unsigned=not x.signed)
            return self.spec_wrap(a, (t, 15, (SIGNED if x.signed else UNSIGNED)[a.ty]))
        if is_float(x.ty) or is_float(a.ty):
            if is_float(x.ty) and is_int(a.ty) and not x.signed:
                return ("(%s)%s" % (SIGNED[x.ty], self.unsigned_operand(a, a.ty)[0]), 14, SIGNED[x.ty])
            return ("(%s)%s" % (SIGNED[x.ty], self.e(a, 14)), 14, SIGNED[x.ty])
        if a.ty == "b":
            return self.ex(a)
        tb, ab = BITS.get(x.ty, 64), BITS.get(a.ty, 64)
        if tb > ab:
            # extension: zero/sign-extend from a's width
            src = (SIGNED if x.signed else UNSIGNED).get(a.ty, "long")
            t, p, ct = self.ex(a)
            if ct == src:
                return (t, p, ct)
            return ("(%s)%s" % (src, t if p >= 14 else "(%s)" % t), 14, src)
        tname = (SIGNED if x.signed else UNSIGNED).get(x.ty, "long")
        t, p, ct = self.ex(a)
        return ("(%s)%s" % (tname, t if p >= 14 else "(%s)" % t), 14, tname)

    # ---------------------------------------------------------- memory
    def mem(self, ld, unsigned=False):
        ty = ld.ty
        T = (UNSIGNED if unsigned else SIGNED).get(ty, "long")
        a = ld.addr
        so = self.sym_struct_access(a, ty, unsigned)
        if so is not None:
            return so[0]
        if isinstance(a, Sym) and a.kind in ("data", "local"):
            g = self.ctx.global_access(a, ty, self.F)
            if g:
                return g
        ta = self.typed_access(a, ty, unsigned)
        if ta is not None:
            return ta[0]
        if isinstance(a, Bin) and a.op == "+":
            base, off = a.a, a.b
            if isinstance(off, Sym) and not isinstance(base, Sym):
                base, off = off, base            # idx*8 + &table  ->  table[idx]
            size = BITS[ty] // 8 if ty in BITS else 8
            idx = None
            if isinstance(off, Bin) and off.op == "<<" and isinstance(off.b, Const) and (1 << off.b.value) == size:
                idx = off.a
            elif isinstance(off, Bin) and off.op == "*" and isinstance(off.b, Const) and off.b.value == size:
                idx = off.a
            elif isinstance(off, Cast) and size == 1:
                idx = off
            elif size == 1 and not isinstance(off, Const):
                idx = off
            if idx is not None:
                if isinstance(base, Sym) and base.kind in ("data", "local") and base.off == 0:
                    bt = self.ctx.array_name(base, ty, self.F)
                    if bt:
                        return "%s[%s]" % (bt, self.e(idx))
                bt, bp, bct = self.ex(base)
                if bct == T + " *":
                    return "%s[%s]" % (self.paren(bt, bp, 15), self.e(idx))
                return "((%s *)%s)[%s]" % (T, self.paren(bt, bp, 14), self.e(idx))
            if isinstance(off, Const) and isinstance(base, Sym) and base.kind == "local":
                pass
            if isinstance(base, Sym) and base.kind in ("data", "local") and not isinstance(off, Const):
                # byte offset from a symbol: keep C pointer arithmetic in bytes
                return "*(%s *)((char *)%s + %s)" % (T, self.e(base, 14), self.e(off, 4))
        at, ap, act = self.ex(a)
        el = act[:-1].strip() if act.endswith("*") else None
        if act == T + " *" or (el is not None and el.endswith("*") and ty == "i64"):
            return "*" + self.paren(at, ap, 14)          # *p, also a loaded pointer (*(char **)q)
        return "*(%s *)%s" % (T, self.paren(at, ap, 14))

    def load(self, x):
        so = self.sym_struct_access(x.addr, x.ty, False)
        if so is not None:
            return so
        ta = self.typed_access(x.addr, x.ty)
        if ta is not None and not (isinstance(x.addr, Sym)):
            return self.spec_wrap(x, ta)
        t = self.mem(x)
        return self.spec_wrap(x, (t, 15, SIGNED.get(x.ty, "long")))

    def spec_wrap(self, ld, r):
        """a speculative load through a pointer that the code tests for NULL:
        on e2k it does not trap, in C it must not be evaluated -> __SPEC(p, x)"""
        if not getattr(ld, "spec", False):
            return r
        sa = split_addr(ld.addr)
        if sa is None or sa[0] not in getattr(self, "nullable", ()):
            return r
        return ("__SPEC(%s, %s)" % (sa[0].name, r[0]), 16, r[2])

    def sym_value(self, x):
        return self.ctx.sym_value(x, self.F)

    def call(self, x):
        args = ", ".join(self.e(a, 2) for a in x.args)
        t = x.target
        if isinstance(t, Sym) and t.kind == "func":
            from .decompiler import cname
            name = cname(t.name)
        elif isinstance(t, Var) and getattr(t.var, "funcptr", None) and t.var.ty == "i64":
            name = t.var.name
        elif isinstance(t, Sym):
            name = "((%s (*)())%s)" % (SIGNED.get(x.ty, "long"), self.e(t, 14))
        else:
            name = "((%s (*)())%s)" % (SIGNED.get(x.ty, "long"), self.e(t, 14))
        return ("%s(%s)" % (name, args), 15, SIGNED.get(x.ty, "long"))

    def intr(self, x):
        n = x.name
        simple = {"smulh": "__smulh", "umulh": "__umulh", "unordered": "__unordered",
                  "lzcnt": "__builtin_clzl" if x.ty == "i64" else "__builtin_clz",
                  "popcnt": "__builtin_popcountl" if x.ty == "i64" else "__builtin_popcount",
                  "fabs": "__builtin_fabs", "fsqrt": "__builtin_sqrt", "fmin": "__builtin_fmin",
                  "fmax": "__builtin_fmax", "parity": "__builtin_parityl",
                  "paddw": "__paddw", "psubw": "__psubw", "pcmpgtw": "__pcmpgtw", "pcmpeqw": "__pcmpeqw",
                  "pfadds": "__pfadds", "pfsubs": "__pfsubs", "pfmuls": "__pfmuls", "pshufb": "__pshufb"}
        fn = simple.get(n, "__e2k_" + n)
        return ("%s(%s)" % (fn, ", ".join(self.e(a, 2) for a in x.args)), 15, SIGNED.get(x.ty, "long"))

    # ---------------------------------------------------------- statements
    def assign_rhs(self, dst, src):
        """right-hand side text converted to the destination's C type where C
        would not do it implicitly (pointer <-> integer, other element type)"""
        t, p, ct = self.ex(src)
        if not isinstance(dst, Var):
            return self.paren(t, p, 2)
        dct = self.vtype(dst.var)
        if dct.endswith("*") and ct != dct and not (isinstance(src, Const) and src.value == 0):
            return "(%s)%s" % (dct, self.paren(t, p, 14))
        if not dct.endswith("*") and ct.endswith("*"):
            return "(%s)%s" % (dct, self.paren(t, p, 14))
        return self.paren(t, p, 2)

    def stmt(self, s):
        if isinstance(s, Assign):
            d = s.dst.var.name if isinstance(s.dst, Var) else self.e(s.dst)
            src = s.src
            line = None
            psize = 1
            if isinstance(s.dst, Var) and self.vtype(s.dst.var).endswith("*"):
                psize = elem_csize(self.vtype(s.dst.var)) or 1
            if psize > 1 and isinstance(src, Bin) and src.op in ("+", "-") and \
                    isinstance(src.a, Var) and src.a.var is s.dst.var:
                k = scale_down(src.b, psize)
                if k is not None:
                    src = Bin(src.op, src.a, k, src.ty)       # p += 4  ->  ++p  (int *p)
                    psize = 1
            if psize == 1 and isinstance(src, Bin) and src.op in ("+", "-", "*", "&", "|", "^", "<<") and \
                    isinstance(src.a, Var) and isinstance(s.dst, Var) and src.a.var is s.dst.var and \
                    (src.op in ("+", "-") or not self.vtype(s.dst.var).endswith("*")):
                if src.op == "+" and isinstance(src.b, Const) and is_int(src.ty):
                    v = sext(src.b.value, BITS[src.ty])
                    if v == 1:
                        line = "++%s;" % d
                    elif v == -1:
                        line = "--%s;" % d
                    elif v < 0:
                        line = "%s -= %s;" % (d, fmt_int(-v, src.ty))
                if line is None:
                    cop = ARITH_C[src.op]
                    line = "%s %s= %s;" % (d, cop, self.e(src.b, 2))
            if line is None:
                line = "%s = %s;" % (d, self.assign_rhs(s.dst, s.src))
        elif isinstance(s, Store):
            val = s.val
            if isinstance(val, Cast) and is_int(val.ty) and is_int(val.a.ty) and BITS[val.a.ty] > BITS[val.ty]:
                val = val.a
            line = "%s = %s;" % (self.mem(Load(s.addr, s.ty)), self.e(val, 2))
        elif isinstance(s, ExprStmt):
            if getattr(s, "asm", None):
                line = "__asm__(\"%s\");" % s.asm.replace('"', "'")
            else:
                line = "%s;" % self.e(s.e)
        elif isinstance(s, Comment):
            line = "/* %s */" % s.text
        else:
            line = "/* %r */" % (s,)
        if s.guard is not None:
            line = "if ( %s ) %s" % (self.e(s.guard), line)
        return line

    def nodes(self, ns, depth, out):
        ind = self.indent * depth
        for n in ns:
            if isinstance(n, SStmt):
                out.append(ind + self.stmt(n.s))
            elif isinstance(n, SLabel):
                out.append("loc_%x:" % n.label)
            elif isinstance(n, SGoto):
                out.append(ind + "goto loc_%x;" % n.label)
            elif isinstance(n, SBreak):
                out.append(ind + "break;")
            elif isinstance(n, SContinue):
                out.append(ind + "continue;")
            elif isinstance(n, SReturn):
                if n.value is None:
                    out.append(ind + "return;")
                else:
                    out.append(ind + "return %s;" % self.e(n.value))
            elif isinstance(n, SRaw):
                if isinstance(n.text, tuple):
                    out.append(ind + n.text[0] % self.e(n.text[1]))
                else:
                    out.append(ind + n.text)
            elif isinstance(n, SIf):
                out.append(ind + "if ( %s )" % self.e(n.cond))
                self.block(n.then, depth, out)
                els = n.els
                while len(els) == 1 and isinstance(els[0], SIf):
                    sub = els[0]
                    out.append(ind + "else if ( %s )" % self.e(sub.cond))
                    self.block(sub.then, depth, out)
                    els = sub.els
                if els:
                    out.append(ind + "else")
                    self.block(els, depth, out)
            elif isinstance(n, SLoop):
                if n.kind == "for":
                    hdr = lambda s: self.stmt(s).rstrip(";") if s is not None else ""
                    out.append(ind + "for ( %s; %s; %s )" % (hdr(n.init), self.e(n.cond), hdr(n.step)))
                    if n.body:
                        self.block(n.body, depth, out)
                    else:
                        out[-1] += ";"
                elif n.kind == "dowhile":
                    out.append(ind + "do")
                    self.block(n.body, depth, out, force=True)
                    out[-1] = out[-1] + " while ( %s );" % self.e(n.cond)
                else:
                    c = "1" if n.cond is None else self.e(n.cond)
                    out.append(ind + "while ( %s )" % c)
                    self.block(n.body, depth, out, force=True)
            elif isinstance(n, SSwitch):
                out.append(ind + "switch ( %s )" % self.e(n.expr))
                out.append(ind + "{")
                for vals, body in n.cases:
                    for v in vals:
                        out.append(ind + "    case %s:" % v)
                    self.nodes(body, depth + 2, out)
                if n.default is not None:
                    out.append(ind + "    default:")
                    self.nodes(n.default, depth + 2, out)
                out.append(ind + "}")

    def block(self, ns, depth, out, force=False):
        ind = self.indent * depth
        if not force and len(ns) == 1 and isinstance(ns[0], (SStmt, SBreak, SContinue, SGoto, SReturn, SRaw)):
            self.nodes(ns, depth + 1, out)
            return
        out.append(ind + "{")
        self.nodes(ns, depth + 1, out)
        out.append(ind + "}")
